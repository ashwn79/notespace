export const EMOJIS: EmojiEntry[] = DATA.map(([c, n, k]) => ({
  c,
  n,
  k: k.split(" "),
}));

/** Search emojis by name / keyword. Empty query → the curated default set. */
export function searchEmojis(query: string, limit = 64): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJIS.slice(0, limit);

  const scored: { entry: EmojiEntry; score: number }[] = [];
  for (const entry of EMOJIS) {
    const name = entry.n.toLowerCase();
    let score = 0;
    if (name.startsWith(q)) score = 4;
    else if (name.includes(q)) score = 3;
    else if (entry.k.some((k) => k === q)) score = 3;
    else if (entry.k.some((k) => k.startsWith(q))) score = 2;
    else if (entry.k.some((k) => k.includes(q))) score = 1.5;
    else if (fuzzyMatch(q, entry.n) || entry.k.some((k) => fuzzyMatch(q, k))) score = 1;
    if (score > 0) scored.push({ entry, score });
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.entry);
}
